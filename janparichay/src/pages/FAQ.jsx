export default function FAQ() {
  const [langDropdownOpen, setLangDropdownOpen] = useState(false)
  const [selectedLang, setSelectedLang] = useState('English')
  const [activeIndex, setActiveIndex] = useState(null) 
  const langRef = useRef(null)

  const languages = [
    { code: 'en', label: 'English' },
    { code: 'ml', label: 'മലയാളം' },
    { code: 'hi', label: 'हिन्दी' },
    { code: 'te', label: 'తెలుగు' },
    { code: 'mr', label: 'मराठी' },
    { code: 'ta', label: 'தமிழ்' },
    { code: 'or', label: 'ଓଡ଼ିଆ' }
  ]

  useEffect(() => {
    function handleClickOutside(e) {
      if (langRef.current && !langRef.current.contains(e.target)) {
        setLangDropdownOpen(false)
      }
    }
    if (langDropdownOpen) {
      document.addEventListener('mousedown', handleClickOutside)
    }
    return () => {
      document.removeEventListener('mousedown', handleClickOutside)
    }
  }, [langDropdownOpen])

  const toggleAccordion = (index) => {
    setActiveIndex(activeIndex === index ? null : index)
  }

  const text = TRANSLATIONS[selectedLang] || TRANSLATIONS.English

  const renderAnswer = (faq) => {
    if (faq.intro) {
      return (
        <div>
          <p style={{ margin: '0 0 12px 0' }}>{faq.intro}</p>
          <ul style={{ paddingLeft: '20px', margin: 0, listStyleType: 'disc' }}>
            {faq.a.map((item, idx) => (
              <li key={idx} style={{ marginBottom: '8px' }}>{item}</li>
            ))}
          </ul>
        </div>
      )
    }
    if (Array.isArray(faq.a)) {
      return (
        <ul style={{ paddingLeft: '20px', margin: 0, listStyleType: 'disc' }}>
          {faq.a.map((item, idx) => (
            <li key={idx} style={{ marginBottom: '8px' }}>{item}</li>
          ))}
        </ul>
      )
    }
    return <p style={{ margin: 0 }}>{faq.a}</p>
  }

  return (
    <div className="faq-page">
      {/* Header */}
      <header className="faq-header">
        <div className="faq-header-logo-container">
          <img src={meriPehchaanLogo} alt="Meri Pehchaan" className="faq-header-logo" />
        </div>
        <div className="faq-header-lang" ref={langRef}>
          <div 
            className="faq-lang-trigger" 
            onClick={() => setLangDropdownOpen(prev => !prev)}
          >
            <span>{selectedLang}</span>
            <i className="bi bi-chevron-down faq-lang-chevron"></i>
          </div>
          {langDropdownOpen && (
            <ul className="faq-lang-menu">
              {languages.map(lang => (
                <li 
                  key={lang.code} 
                  className={`faq-lang-item ${selectedLang === lang.label ? 'active' : ''}`}
                  onClick={() => {
                    setSelectedLang(lang.label)
                    setLangDropdownOpen(false)
                  }}
                >
                  {lang.label}
                </li>
              ))}
            </ul>
          )}
        </div>
      </header>

      {/* Scrollable Content Wrapper */}
      <div className="faq-content-wrapper">
        <div className="faq-body">
          <h1 className="faq-title">{text.title}</h1>
          
          <div className="faq-list">
            {text.faqs.map((faq, index) => {
              const isOpen = activeIndex === index
              return (
                <div key={index} className={`faq-item ${isOpen ? 'active' : ''}`}>
                  <button 
                    className="faq-question-btn" 
                    onClick={() => toggleAccordion(index)}
                    aria-expanded={isOpen}
                  >
                    <span className="faq-question-text">{faq.q}</span>
                    <i className="bi bi-chevron-down faq-chevron"></i>
                  </button>
                  <div className="faq-answer-container">
                    <div className="faq-answer-content">
                      {renderAnswer(faq)}
                    </div>
                  </div>
                </div>
              )
            })}
          </div>
        </div>
      </div>

      <Footer showSlider={true} />
    </div>
  )
}
